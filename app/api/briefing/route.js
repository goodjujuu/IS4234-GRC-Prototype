import { NextResponse } from 'next/server';
import { buildBriefingFacts, simulatedSummary } from '@/lib/briefing';
import { aiSummary } from '@/lib/briefingAi';
import { getNow, latestScores, loadConfig, pressureAt, tick } from '@/lib/engine';
import { prisma } from '@/lib/prisma';
import { apiUser } from '@/lib/session';

export const maxDuration = 90;

// Generates an informational briefing on demand, ready to read immediately.
export async function POST() {
  const { error } = await apiUser(['CONDUCT_RISK']);
  if (error) return error;
  const now = await getNow(prisma);
  const config = await loadConfig(prisma);
  const [latest] = await latestScores(prisma);
  if (!latest) return NextResponse.json({ error: 'Load scoring data before generating a briefing.' }, { status: 409 });
  const pressure = await pressureAt(prisma, latest.asOf, config);
  const previousPressure = await pressureAt(prisma, new Date(latest.asOf.getTime() - 1), config);
  const facts = await buildBriefingFacts(prisma, { now, pressure, previousPressure });
  const { text, reason, model } = await aiSummary(facts);
  const draft = text || simulatedSummary(facts);
  const createdAt = await tick(prisma);
  const source = text ? 'AI_MODEL' : 'SIMULATED';
  const generation = { provider: 'GOOGLE_GEMINI', model, fallbackReason: reason || null };
  await prisma.briefing.create({ data: { asOf: now, facts: { ...facts, generation }, draft, summary: draft, source, createdAt } });
  return NextResponse.json({ source, message: text ? 'New briefing generated by Google AI.' : `A template summary is shown. ${reason}` });
}
