import { NextResponse } from 'next/server';
import { buildBriefingFacts, simulatedSummary } from '@/lib/briefing';
import { aiSummary } from '@/lib/briefingAi';
import { getNow, latestScores, loadConfig, pressureAt } from '@/lib/engine';
import { prisma } from '@/lib/prisma';
import { apiUser } from '@/lib/session';

// Generates a briefing on demand. The AI draft stays unconfirmed until a reviewer confirms
// or corrects it.
export async function POST() {
  const { error } = await apiUser(['CONDUCT_RISK']);
  if (error) return error;
  const now = await getNow(prisma);
  const config = await loadConfig(prisma);
  const pressure = await pressureAt(prisma, now, config);
  const [latest] = await latestScores(prisma);
  const previousPressure = await pressureAt(prisma, new Date(latest.asOf.getTime() - 1), config);
  const facts = await buildBriefingFacts(prisma, { now, pressure, previousPressure });
  const { text, reason } = await aiSummary(facts);
  const draft = text || simulatedSummary(facts);
  await prisma.briefing.create({ data: { asOf: now, facts, draft, summary: draft, source: text ? 'AI_MODEL' : 'SIMULATED', createdAt: now } });
  return NextResponse.json({ message: text ? 'New briefing generated by the AI model. A reviewer must confirm or correct it.' : `New briefing generated with the simulated draft. ${reason}` });
}
